@dataclass
class GhostConfig:
    """Runtime configuration for GhostShell.

    Attributes:
        app_name: Name of the application.
        version: Current semantic version.
        tagline: Descriptive tagline for the challenge.
        startup_animation: Whether to play the CRT boot-up sequence on launch.
        animation_speed: Per-step delay in seconds during animations.
        prompt_text: Prompt symbol displayed to the user.
        model_endpoint: URL of the local OpenAI-compatible endpoint.
        model_name: Model identifier expected by the local server.
        model_timeout: HTTP request timeout in seconds.
        model_system_prompt: System prompt instructing the ghost persona.
        force_placeholder: If True, bypass the local model and use Phase 1 placeholder.
        allow_command_execution: Security flag; must always be False.
    """

    app_name: str = "GhostShell"
    version: str = "0.3.0"
    tagline: str = "The Ghost in the Machine — Possessed Local-First AI Developer Assistant"
    startup_animation: bool = True
    animation_speed: float = 0.03
    prompt_text: str = "👻 ghostshell › "
    model_endpoint: str = DEFAULT_MODEL_ENDPOINT
    model_name: str = DEFAULT_MODEL_NAME
    model_timeout: float = DEFAULT_MODEL_TIMEOUT
    model_system_prompt: str = DEFAULT_SYSTEM_PROMPT
    force_placeholder: bool = False
    allow_command_execution: bool = field(init=False, default=ALLOW_COMMAND_EXECUTION)

    def __setattr__(self, name: str, value: object) -> None:
        """Prevent overriding the security invariant."""
        if name == "allow_command_execution" and value is not False:
            raise ValueError(
                "Security Violation: Command execution cannot be enabled in GhostShell."
            )
        super().__setattr__(name, value)


def get_default_config() -> GhostConfig:
    """Return the default configuration for GhostShell with env overrides."""
    no_anim = os.environ.get("GHOSTSHELL_NO_ANIMATION", "").lower() in ("1", "true", "yes")
    endpoint = os.environ.get("GHOSTSHELL_MODEL_ENDPOINT", DEFAULT_MODEL_ENDPOINT)
    model_name = os.environ.get("GHOSTSHELL_MODEL_NAME", DEFAULT_MODEL_NAME)
    force_placeholder = os.environ.get("GHOSTSHELL_PLACEHOLDER", "").lower() in ("1", "true", "yes")

    try:
        timeout = float(os.environ.get("GHOSTSHELL_MODEL_TIMEOUT", str(DEFAULT_MODEL_TIMEOUT)))
    except ValueError:
        timeout = DEFAULT_MODEL_TIMEOUT

    return GhostConfig(
        startup_animation=not no_anim,
        model_endpoint=endpoint,
        model_name=model_name,
        model_timeout=timeout,
        force_placeholder=force_placeholder,
    )


def enable_windows_virtual_terminal() -> None:
    """Enable VT100 / Virtual Terminal processing in Windows conhost."""
    if sys.platform == "win32":
        try:
            import ctypes
            kernel32 = ctypes.windll.kernel32
            h_out = kernel32.GetStdHandle(-11)  # STD_OUTPUT_HANDLE
            if h_out and h_out != -1:
                mode = ctypes.c_ulong()
                if kernel32.GetConsoleMode(h_out, ctypes.byref(mode)):
                    # 0x0004: ENABLE_VIRTUAL_TERMINAL_PROCESSING
                    # 0x0001: ENABLE_PROCESSED_OUTPUT
                    # 0x0002: ENABLE_WRAP_AT_EOL_OUTPUT
                    kernel32.SetConsoleMode(h_out, mode.value | 0x0004 | 0x0001 | 0x0002)
        except Exception:
            pass


def create_console(config: GhostConfig | None = None) -> Console:
    """Instantiate and configure a Rich Console tailored for GhostShell.

    Ensures UTF-8 encoding support on Windows terminals, enables virtual terminal
    processing to prevent cursor drift and line wrap glitches on window moving/resizing,
    and binds the spectral phosphor theme.

    Args:
        config: Optional GhostConfig instance.

    Returns:
        A pre-configured Console object.
    """
    enable_windows_virtual_terminal()

    if sys.platform == "win32":
        for stream_name in ("stdout", "stderr"):
            stream = getattr(sys, stream_name, None)
            if stream and hasattr(stream, "reconfigure"):
                try:
                    stream.reconfigure(encoding="utf-8", errors="replace")
                except Exception:
                    pass

    return Console(
        theme=GHOST_THEME,
        color_system="auto",
        highlight=False,
        safe_box=True,
    )
