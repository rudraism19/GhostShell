"""Configuration management and visual themes for GhostShell.

Provides color palettes, theme bindings for Rich, and runtime settings.
Enforces the core security invariant that command execution is strictly forbidden.
"""

from __future__ import annotations

import os
import sys
from dataclasses import dataclass, field
from typing import Final

from rich.console import Console
from rich.theme import Theme


# ==============================================================================
# Security Invariants
# ==============================================================================
# In accordance with Requirement 7: Never execute commands supplied by the user
# or generated by the AI. This flag is immutable and strictly False.
ALLOW_COMMAND_EXECUTION: Final[bool] = False


# ==============================================================================
# Spectral Phosphor Color Palette (CRT Green & Eerie Accents)
# ==============================================================================
PHOSPHOR_GREEN: Final[str] = "#00FF66"       # Vivid CRT phosphor glow
PHOSPHOR_BRIGHT: Final[str] = "#39FF14"      # High-voltage spectral neon
PHANTOM_DIM: Final[str] = "#2D7D46"          # Background terminal matrix green
PHANTOM_DEEP: Final[str] = "#14301B"         # Shadow / muted green
SPECTRAL_CYAN: Final[str] = "#00F0FF"        # Ectoplasmic digital pulse
ECTO_AMBER: Final[str] = "#FFB000"           # Warning / supernatural flux
CRIMSON_GLITCH: Final[str] = "#FF3366"       # Anomaly / error alert
GHOST_MIST: Final[str] = "#E0FFE5"           # Ghostly white text
DARK_BG: Final[str] = "#0A100A"              # Deep void background


# ==============================================================================
# Rich Theme Mapping
# ==============================================================================
GHOST_THEME = Theme(
    {
        "ghost.primary": f"bold {PHOSPHOR_GREEN}",
        "ghost.bright": f"bold {PHOSPHOR_BRIGHT}",
        "ghost.dim": f"{PHANTOM_DIM}",
        "ghost.accent": f"bold {SPECTRAL_CYAN}",
        "ghost.warn": f"bold {ECTO_AMBER}",
        "ghost.error": f"bold {CRIMSON_GLITCH}",
        "ghost.text": f"{GHOST_MIST}",
        "ghost.prompt": f"bold {PHOSPHOR_GREEN}",
        "ghost.command": f"bold {SPECTRAL_CYAN}",
        "ghost.border": f"{PHOSPHOR_GREEN}",
        "ghost.border.dim": f"{PHANTOM_DIM}",
        "ghost.panel.title": f"bold {PHOSPHOR_BRIGHT}",
    }
)


@dataclass
class GhostConfig:
    """Runtime configuration for GhostShell.

    Attributes:
        app_name: Name of the application.
        version: Current semantic version.
        tagline: Descriptive tagline for the challenge.
        startup_animation: Whether to play the CRT boot-up sequence on launch.
        animation_speed: Per-step delay in seconds during animations.
        prompt_text: Prompt symbol displayed to the user.
        allow_command_execution: Security flag; must always be False.
    """

    app_name: str = "GhostShell"
    version: str = "0.1.0"
    tagline: str = "The Ghost in the Machine — Local-First AI Developer Assistant"
    startup_animation: bool = True
    animation_speed: float = 0.03
    prompt_text: str = "👻 ghostshell › "
    allow_command_execution: bool = field(init=False, default=ALLOW_COMMAND_EXECUTION)

    def __setattr__(self, name: str, value: object) -> None:
        """Prevent overriding the security invariant."""
        if name == "allow_command_execution" and value is not False:
            raise ValueError(
                "Security Violation: Command execution cannot be enabled in GhostShell."
            )
        super().__setattr__(name, value)


def get_default_config() -> GhostConfig:
    """Return the default configuration for GhostShell."""
    # Check environment variable for animation override (useful in CI or test runners)
    no_anim = os.environ.get("GHOSTSHELL_NO_ANIMATION", "").lower() in ("1", "true", "yes")
    return GhostConfig(
        startup_animation=not no_anim,
    )


def create_console(config: GhostConfig | None = None) -> Console:
    """Instantiate and configure a Rich Console tailored for GhostShell.

    Ensures UTF-8 encoding support on Windows terminals and binds the spectral
    phosphor theme.

    Args:
        config: Optional GhostConfig instance.

    Returns:
        A pre-configured Console object.
    """
    # Ensure Windows console uses UTF-8 if reconfigurable
    if sys.platform == "win32":
        try:
            if hasattr(sys.stdout, "reconfigure"):
                sys.stdout.reconfigure(encoding="utf-8")
            if hasattr(sys.stderr, "reconfigure"):
                sys.stderr.reconfigure(encoding="utf-8")
        except Exception:
            # Fallback gracefully if standard handles cannot be reconfigured
            pass

    return Console(
        theme=GHOST_THEME,
        color_system="auto",
        highlight=False,
    )
