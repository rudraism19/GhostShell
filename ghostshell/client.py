"""Modular local HTTP client for Gemma inference via llama.cpp server.

Communicates with the OpenAI-compatible endpoint without external dependencies,
ensuring 100% local-first, zero-cloud execution on Windows.
"""

from __future__ import annotations

import json
import time
import urllib.error
import urllib.request
from dataclasses import dataclass
from typing import Any


class ModelServerError(Exception):
    """Raised when communication with the local model server fails."""

    def __init__(
        self,
        message: str,
        is_offline: bool = False,
        status_code: int | None = None,
        endpoint: str | None = None,
    ) -> None:
        super().__init__(message)
        self.message = message
        self.is_offline = is_offline
        self.status_code = status_code
        self.endpoint = endpoint


@dataclass
class CompletionResponse:
    """Structured response from the local model server.

    Attributes:
        content: The text output generated by Gemma.
        model: Identifier of the model that generated the completion.
        prompt_tokens: Number of prompt tokens reported by the server.
        completion_tokens: Number of generated tokens reported by the server.
        total_tokens: Total token count.
        latency_ms: Round-trip request time in milliseconds.
    """

    content: str
    model: str
    prompt_tokens: int
    completion_tokens: int
    total_tokens: int
    latency_ms: float


class GemmaClient:
    """Client for local llama.cpp server with OpenAI-compatible endpoint."""

    def __init__(
        self,
        endpoint: str = "http://127.0.0.1:8080/v1/chat/completions",
        model_name: str = "gemma-3-1b-it",
        timeout: float = 45.0,
    ) -> None:
        """Initialize the local Gemma client.

        Args:
            endpoint: Full URL to the chat completions endpoint.
            model_name: Name of the model.
            timeout: Request timeout in seconds.
        """
        self.endpoint = endpoint
        self.model_name = model_name
        self.timeout = timeout

    def check_health(self, timeout: float = 2.0) -> bool:
        """Check whether the local llama.cpp server is reachable.

        Args:
            timeout: Probe timeout in seconds.

        Returns:
            True if the server responded, False otherwise.
        """
        # Determine base URL for health check
        base_url = self.endpoint.split("/v1/")[0] if "/v1/" in self.endpoint else self.endpoint
        health_urls = [f"{base_url}/health", f"{base_url}/v1/models", self.endpoint]

        for url in health_urls:
            try:
                req = urllib.request.Request(url, method="GET")
                with urllib.request.urlopen(req, timeout=timeout) as resp:
                    if resp.status in (200, 204, 404, 405):
                        return True
            except urllib.error.HTTPError as exc:
                # If the server returned an HTTP error code (e.g. 404/405), the daemon is running!
                if exc.code in (200, 400, 404, 405):
                    return True
            except Exception:
                continue

        return False

    def chat_completion(
        self,
        messages: list[dict[str, str]],
        temperature: float = 0.7,
        max_tokens: int = 1024,
    ) -> CompletionResponse:
        """Send a chat completion request to the local llama.cpp server.

        Args:
            messages: List of message dictionaries with 'role' and 'content'.
            temperature: Sampling temperature.
            max_tokens: Maximum tokens to generate.

        Returns:
            CompletionResponse containing Gemma's generated text and usage stats.

        Raises:
            ModelServerError: If the server is offline, times out, or returns an error.
        """
        payload: dict[str, Any] = {
            "model": self.model_name,
            "messages": messages,
            "temperature": temperature,
            "max_tokens": max_tokens,
            "stream": False,
        }

        data_bytes = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            self.endpoint,
            data=data_bytes,
            headers={
                "Content-Type": "application/json",
                "User-Agent": "GhostShell/0.3.0 (Local-First Assistant)",
            },
            method="POST",
        )

        start_time = time.perf_counter()

        try:
            with urllib.request.urlopen(req, timeout=self.timeout) as resp:
                elapsed_ms = (time.perf_counter() - start_time) * 1000.0
                raw_body = resp.read().decode("utf-8")
        except urllib.error.HTTPError as exc:
            err_body = ""
            try:
                err_body = exc.read().decode("utf-8")
            except Exception:
                pass
            raise ModelServerError(
                message=f"HTTP {exc.code} from local model server: {exc.reason}. {err_body}".strip(),
                is_offline=False,
                status_code=exc.code,
                endpoint=self.endpoint,
            ) from exc
        except (urllib.error.URLError, ConnectionRefusedError, TimeoutError, OSError) as exc:
            # Server not running or connection refused
            raise ModelServerError(
                message=(
                    f"Unable to connect to local model server at {self.endpoint}. "
                    f"Underlying cause: {exc}"
                ),
                is_offline=True,
                endpoint=self.endpoint,
            ) from exc
        except Exception as exc:
            raise ModelServerError(
                message=f"Unexpected transmission disturbance with model server: {exc}",
                is_offline=True,
                endpoint=self.endpoint,
            ) from exc

        # Parse JSON response
        try:
            resp_data = json.loads(raw_body)
        except json.JSONDecodeError as exc:
            raise ModelServerError(
                message=f"Invalid JSON received from model server: {exc}",
                is_offline=False,
                endpoint=self.endpoint,
            ) from exc

        choices = resp_data.get("choices")
        if not choices or not isinstance(choices, list):
            raise ModelServerError(
                message="Model server returned response without valid completion choices.",
                is_offline=False,
                endpoint=self.endpoint,
            )

        content = choices[0].get("message", {}).get("content", "")
        model_used = resp_data.get("model", self.model_name)
        usage = resp_data.get("usage", {})
        prompt_tokens = usage.get("prompt_tokens", 0)
        completion_tokens = usage.get("completion_tokens", 0)
        total_tokens = usage.get("total_tokens", prompt_tokens + completion_tokens)

        return CompletionResponse(
            content=content.strip(),
            model=model_used,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=total_tokens,
            latency_ms=round(elapsed_ms, 2),
        )
